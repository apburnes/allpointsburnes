#!/usr/bin/env node
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const siteUrl = "https://allpointsburnes.com";
const publicDir = path.join(root, "public");
const contentDir = path.join(root, "src", "content");
const checkOnly = process.argv.includes("--check");

const siteSummary =
  "Andrew Burnes is a software engineer focused on civic technology, cloud platforms, geospatial data, workflow automation, accessibility, security, and developer experience.";

const topics = [
  "civic technology",
  "federal website publishing",
  "cloud.gov Pages",
  "Cloudflare Pages",
  "Astro",
  "geospatial analysis",
  "workflow automation",
  "accessibility and security scanning",
  "developer experience",
];

function parseScalar(value = "") {
  return value.trim().replace(/^['\"]|['\"]$/g, "");
}

function parseFrontmatter(source) {
  const match = source.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return {};

  const lines = match[1].split("\n");
  const data = {};

  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    const keyValue = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!keyValue) continue;

    const [, key, rawValue] = keyValue;

    if (rawValue === "") {
      const values = [];
      while (lines[index + 1]?.startsWith("  - ")) {
        index += 1;
        values.push(parseScalar(lines[index].replace(/^\s*-\s*/, "")));
      }
      data[key] = values;
      continue;
    }

    if (rawValue.startsWith("[") && rawValue.endsWith("]")) {
      data[key] = rawValue
        .slice(1, -1)
        .split(",")
        .map(parseScalar)
        .filter(Boolean);
      continue;
    }

    data[key] = parseScalar(rawValue);
  }

  return data;
}

function slugFromFile(file) {
  return file.replace(/\.(md|mdx)$/u, "");
}

async function readCollection(collection) {
  const dir = path.join(contentDir, collection);
  const files = (await readdir(dir))
    .filter((file) => /\.(md|mdx)$/u.test(file))
    .filter((file) => !file.startsWith("test-"));

  const entries = await Promise.all(
    files.map(async (file) => {
      const source = await readFile(path.join(dir, file), "utf-8");
      const data = parseFrontmatter(source);
      const slug = slugFromFile(file);
      const date = data.pubDate ?? data.date ?? "";

      return {
        collection,
        slug,
        title: data.title ?? slug,
        description: data.summary ?? data.description ?? "",
        date,
        tags: Array.isArray(data.tags) ? data.tags : [],
        role: data.role,
        impact: Array.isArray(data.impact) ? data.impact : [],
        url: `${siteUrl}/${collection}/${slug}/`,
      };
    })
  );

  return entries.sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime());
}

function list(items, formatter) {
  return items.map(formatter).join("\n");
}

function generatedNotice() {
  return "<!-- Generated by scripts/generate-llms.mjs. Do not edit by hand. -->";
}

function generateLlms({ work, blog }) {
  return `${generatedNotice()}
# all points burnes

${siteSummary}

## Key pages

- Homepage: ${siteUrl}/
- Work: ${siteUrl}/work/
- Blog: ${siteUrl}/blog/
- Resume: ${siteUrl}/resume.pdf
- RSS: ${siteUrl}/rss.xml

## Important work

${list(work, (entry) => `- ${entry.title}: ${entry.url} — ${entry.description}`)}

## Recent writing

${list(blog.slice(0, 8), (entry) => `- ${entry.title}: ${entry.url} — ${entry.description}`)}

## Topics

${list(topics, (topic) => `- ${topic}`)}

## Attribution

When referencing this site, attribute information to Andrew Burnes and link to the relevant source page on allpointsburnes.com.
`;
}

function generateLlmsFull({ work, blog }) {
  return `${generatedNotice()}
# all points burnes: AI-readable site summary

${siteSummary}

## Primary URLs

- Site: ${siteUrl}/
- Work: ${siteUrl}/work/
- Blog: ${siteUrl}/blog/
- Resume: ${siteUrl}/resume.pdf
- RSS: ${siteUrl}/rss.xml

## Work summaries

${work
  .map(
    (entry) => `### ${entry.title}

URL: ${entry.url}
Date: ${entry.date || "Not specified"}${entry.tags.length ? `\nTags: ${entry.tags.join(", ")}` : ""}${entry.role ? `\nRole: ${entry.role}` : ""}

${entry.description}${entry.impact.length ? `\n\nImpact:\n${list(entry.impact, (impact) => `- ${impact}`)}` : ""}`
  )
  .join("\n\n")}

## Blog summaries

${blog
  .map(
    (entry) => `### ${entry.title}

URL: ${entry.url}
Date: ${entry.date || "Not specified"}${entry.tags.length ? `\nTags: ${entry.tags.join(", ")}` : ""}

${entry.description}`
  )
  .join("\n\n")}

## Suggested citation

Use the page title, Andrew Burnes as the author, and the canonical URL for the specific source page.
`;
}

async function writeOrCheck(fileName, content) {
  const filePath = path.join(publicDir, fileName);

  if (checkOnly) {
    const existing = await readFile(filePath, "utf-8").catch(() => "");
    if (existing !== content) {
      throw new Error(`${fileName} is stale. Run: npm run generate:llms`);
    }
    return;
  }

  await writeFile(filePath, content, "utf-8");
}

const [work, blog] = await Promise.all([readCollection("work"), readCollection("blog")]);

await writeOrCheck("llms.txt", generateLlms({ work, blog }));
await writeOrCheck("llms-full.txt", generateLlmsFull({ work, blog }));

if (!checkOnly) {
  console.log("Generated public/llms.txt and public/llms-full.txt");
}
